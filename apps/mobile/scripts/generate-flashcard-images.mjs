// Regenerates src/lib/filters/flashcards.generated.ts: cartoon pictures for
// the toddler flashcard filter (gpt-image-1), committed as data URIs.
// Manual, not CI — needs an OpenAI key and is non-deterministic:
//
//   cd apps/os && doppler run -- sh -c 'cd ../mobile && node scripts/generate-flashcard-images.mjs'

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const apiKey = process.env.OPENAI_API_KEY;
if (!apiKey) throw new Error("OPENAI_API_KEY is not set");

// Keep in sync with the FLASHCARDS list in lib/filters/definitions.ts
// (color-swatch cards are drawn, not generated).
const WORDS = [
  "dog",
  "cat",
  "ball",
  "banana",
  "apple",
  "water",
  "milk",
  "baby",
  "tomato",
  "cucumber",
  "door",
  "chair",
  "bed",
  "cow",
  "pig",
  "horse",
  "sheep",
  "duck",
  "chicken",
  "carrot",
  "pasta",
  "bread",
  "cheese",
  "egg",
  "strawberry",
  "grapes",
  "orange",
  "car",
  "bus",
  "train",
  "book",
  "star",
  "moon",
  "sun",
  "tree",
  "flower",
  "fish",
  "bird",
  "shoe",
  "hat",
  "spoon",
];

const scratch = mkdtempSync(join(tmpdir(), "flashcards-"));

async function generate(word) {
  const prompt = `Cute, simple, friendly cartoon illustration of ${
    word === "water" ? "a glass of water" : word === "milk" ? "a glass of milk" : `a ${word}`
  } for a toddler flashcard. Single object centered, bold outlines, flat bright colors, plain solid very light background, no text, no letters, no people unless the word is baby.`;
  const response = await fetch("https://api.openai.com/v1/images/generations", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` },
    body: JSON.stringify({
      model: "gpt-image-1",
      prompt,
      size: "1024x1024",
      quality: "low",
      output_format: "jpeg",
    }),
  });
  if (!response.ok) throw new Error(`${word}: ${response.status} ${await response.text()}`);
  const payload = await response.json();
  const raw = join(scratch, `${word}.jpg`);
  writeFileSync(raw, Buffer.from(payload.data[0].b64_json, "base64"));
  execFileSync("sips", [
    "-Z",
    "448",
    "-s",
    "format",
    "jpeg",
    "-s",
    "formatOptions",
    "62",
    raw,
    "--out",
    raw,
  ]);
  const base64 = readFileSync(raw).toString("base64");
  console.log(`${word}: ${Math.round((base64.length * 3) / 4 / 1024)}KB`);
  return [word, base64];
}

// Modest parallelism to stay clear of image-endpoint rate limits.
const results = [];
for (let i = 0; i < WORDS.length; i += 4) {
  results.push(...(await Promise.all(WORDS.slice(i, i + 4).map(generate))));
}

const outPath = new URL("../src/lib/filters/flashcards.generated.ts", import.meta.url).pathname;
writeFileSync(
  outPath,
  `// Generated by scripts/generate-flashcard-images.mjs — do not edit by hand.
// AI-generated (gpt-image-1) toddler flashcard pictures, inlined as data
// URIs. ONLY import this via lib/filters/definitions.ts (the DOM-component
// side) — it must not ride into the native Hermes bundle.

export const FLASHCARD_IMAGES: Record<string, string> = {
${results.map(([word, base64]) => `  ${JSON.stringify(word)}:\n    "data:image/jpeg;base64,${base64}",`).join("\n")}
};
`,
);
console.log(`wrote ${outPath} (${results.length} cards)`);
