// Native JavaScriptCore runs the same filter logic as the browser. Bundle it
// as source text in the OTA so changing a filter doesn't require a native build.
const { build } = require("esbuild");
const { readFileSync, writeFileSync } = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
module.exports = async function buildNativeFilters() {
  const result = await build({
    entryPoints: [path.join(root, "src/lib/filters/native-engine.ts")],
    bundle: true,
    format: "iife",
    globalName: "NativeFilters",
    platform: "neutral",
    target: "es2020",
    minify: true,
    write: false,
    plugins: [
      {
        name: "native-filter-graphics",
        setup(build) {
          build.onResolve({ filter: /^\.\/graphics\.ts$/ }, () => ({
            path: path.join(root, "src/lib/filters/native-graphics.ts"),
          }));
        },
      },
    ],
  });
  const text = `// Generated by scripts/build-native-filters.cjs; Metro refreshes this before bundling.\nexport const NATIVE_FILTER_SOURCE = ${JSON.stringify(result.outputFiles[0].text)};\n`;
  const output = path.join(root, "src/lib/filters/native-runtime.generated.ts");
  const { format } = await import("oxfmt");
  const formatted = await format(output, text);
  if (formatted.errors.length) throw new Error(JSON.stringify(formatted.errors));
  let previous = "";
  try {
    previous = readFileSync(output, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (previous !== formatted.code) writeFileSync(output, formatted.code);
  return result.outputFiles[0].text;
};
if (require.main === module) module.exports();
