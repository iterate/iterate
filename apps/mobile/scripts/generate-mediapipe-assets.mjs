// Regenerates src/lib/filters/mediapipe-assets.generated.ts: the MediaPipe
// face-tracking runtime (wasm loader + wasm binary, read from the installed
// @mediapipe/tasks-vision package so they always match its version) and the
// face_landmarker model (downloaded from Google's model bucket), gzipped and
// committed as base64. The WebView filter pipeline decompresses them at
// runtime (DecompressionStream) so face tracking needs no network and no
// cross-origin fetches — remote ESM imports don't work from the file://
// pages release builds host DOM components on. Manual, not CI:
//
//   node scripts/generate-mediapipe-assets.mjs

import { gzipSync } from "node:zlib";
import { readFileSync, writeFileSync } from "node:fs";

const MODEL_URL =
  "https://storage.googleapis.com/mediapipe-models/face_landmarker/face_landmarker/float16/1/face_landmarker.task";

// The package's exports map hides subpaths from require.resolve; the direct
// node_modules path works because tasks-vision is a direct dependency here.
const resolve = (subpath) =>
  new URL(`../node_modules/@mediapipe/tasks-vision/${subpath}`, import.meta.url).pathname;

const version = JSON.parse(readFileSync(resolve("package.json"), "utf8")).version;
const loaderJs = readFileSync(resolve("wasm/vision_wasm_internal.js"));
const wasm = readFileSync(resolve("wasm/vision_wasm_internal.wasm"));
const model = Buffer.from(await (await fetch(MODEL_URL)).arrayBuffer());

const entry = (name, buffer) => {
  const gz = gzipSync(buffer, { level: 9 });
  console.log(
    `${name}: ${Math.round(buffer.length / 1024)}KB -> ${Math.round(gz.length / 1024)}KB gz`,
  );
  return `export const ${name} = "${gz.toString("base64")}";`;
};

const outPath = new URL("../src/lib/filters/mediapipe-assets.generated.ts", import.meta.url)
  .pathname;
writeFileSync(
  outPath,
  `// Generated by scripts/generate-mediapipe-assets.mjs — do not edit by hand.
// MediaPipe tasks-vision ${version} wasm runtime + face_landmarker model,
// gzip + base64. ONLY import this from the filter-camera DOM component — it
// must never ride into the native Hermes bundle.

export const MEDIAPIPE_TASKS_VISION_VERSION = "${version}";

${entry("MEDIAPIPE_WASM_LOADER_JS_GZ", loaderJs)}

${entry("MEDIAPIPE_WASM_GZ", wasm)}

${entry("FACE_LANDMARKER_MODEL_GZ", model)}
`,
);
console.log(`wrote ${outPath}`);
