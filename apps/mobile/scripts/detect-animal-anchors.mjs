// Regenerates src/lib/filters/animal-anchors.generated.ts: eye/mouth
// positions for each Animal-mask portrait, found by a vision model instead
// of human eyeballing (which shipped a lion wearing its eyes on its cheeks).
// Run AFTER generate-animal-faces.mjs regenerates art, then visually verify
// (the mask drawer's ?debugAnchors harness view) — hand overrides live in
// definitions.ts. Manual, not CI:
//
//   cd apps/os && doppler run -- sh -c 'cd ../mobile && node scripts/detect-animal-anchors.mjs'

import { readFileSync, writeFileSync } from "node:fs";

const apiKey = process.env.OPENAI_API_KEY;
if (!apiKey) throw new Error("OPENAI_API_KEY is not set");

const source = readFileSync(
  new URL("../src/lib/filters/animal-faces.generated.ts", import.meta.url),
  "utf8",
);
const images = [
  ...source.matchAll(/(?:"([^"]+)"|([A-Za-z]\w*)):\s*\n?\s*"(data:image\/png;base64,[^"]+)"/g),
].map((match) => ({ id: match[1] || match[2], dataUri: match[3] }));
if (images.length === 0) throw new Error("No animal images found — generate them first");

async function detect({ id, dataUri }) {
  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` },
    body: JSON.stringify({
      model: "gpt-4o",
      temperature: 0,
      response_format: { type: "json_object" },
      messages: [
        {
          role: "user",
          content: [
            {
              type: "text",
              text: `This is a square photo of a ${id}'s face looking at the camera. Find these landmarks precisely and answer with STRICT JSON only:
{"leftEye": {"x": .., "y": ..}, "rightEye": {"x": .., "y": ..}, "mouth": {"x": .., "y": ..}, "eyeWidth": .., "mouthWidth": ..}
All values are FRACTIONS of the image size between 0 and 1 (x from left edge, y from top edge).
- leftEye / rightEye: the CENTER of each eyeball (viewer's left = leftEye). Look carefully at where the actual eyes are, not where they usually are on such an animal.
- mouth: the point where the lips part (the mouth opening), NOT the nose.
- eyeWidth: one eye's width as a fraction of image width, with ~30% margin.
- mouthWidth: the mouth's width as a fraction of image width.`,
            },
            { type: "image_url", image_url: { url: dataUri, detail: "high" } },
          ],
        },
      ],
    }),
  });
  if (!response.ok) throw new Error(`${id}: ${response.status} ${await response.text()}`);
  const payload = await response.json();
  const anchors = JSON.parse(payload.choices[0].message.content);
  console.log(id, JSON.stringify(anchors));
  return [id, anchors];
}

const results = [];
for (const image of images) results.push(await detect(image));

const outPath = new URL("../src/lib/filters/animal-anchors.generated.ts", import.meta.url).pathname;
writeFileSync(
  outPath,
  `// Generated by scripts/detect-animal-anchors.mjs — do not edit by hand
// (hand overrides go in definitions.ts). Vision-model-detected eye/mouth
// landmarks for the Animal mask portraits; regenerate whenever the art
// regenerates.

export type AnimalAnchors = {
  leftEye: { x: number; y: number };
  rightEye: { x: number; y: number };
  mouth: { x: number; y: number };
  eyeWidth: number;
  mouthWidth: number;
};

export const ANIMAL_ANCHORS: Record<string, AnimalAnchors> = ${JSON.stringify(Object.fromEntries(results), null, 2)};
`,
);
console.log(`wrote ${outPath}`);
