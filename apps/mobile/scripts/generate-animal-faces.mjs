// Regenerates src/lib/filters/animal-faces.generated.ts: photorealistic
// animal face portraits (transparent background) for the Animal mask filter,
// committed as data URIs. The eye/mouth anchor points live hand-tuned in
// definitions.ts (ANIMAL_FACES) — regenerating art means re-checking them.
// Manual, not CI:
//
//   cd apps/os && doppler run -- sh -c 'cd ../mobile && node scripts/generate-animal-faces.mjs'

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const apiKey = process.env.OPENAI_API_KEY;
if (!apiKey) throw new Error("OPENAI_API_KEY is not set");

const ANIMALS = [
  "cat",
  "dog",
  "goat",
  "tiger",
  "bear",
  "monkey",
  "gorilla",
  "lion",
  "horse",
  "fox",
  "mouse",
];

const scratch = mkdtempSync(join(tmpdir(), "animal-faces-"));

// Merge mode: keep approved art, generate only missing animals.
const outPath = new URL("../src/lib/filters/animal-faces.generated.ts", import.meta.url).pathname;
const existing = new Map();
try {
  for (const match of readFileSync(outPath, "utf8").matchAll(
    /(?:"([^"]+)"|([A-Za-z]\w*)):\s*\n?\s*"data:image\/png;base64,([^"]+)"/g,
  )) {
    existing.set(match[1] || match[2], match[3]);
  }
} catch {
  // no existing file
}
console.log(`${existing.size} existing faces kept`);

async function generate(animal) {
  if (existing.has(animal)) return [animal, existing.get(animal)];
  const response = await fetch("https://api.openai.com/v1/images/generations", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` },
    body: JSON.stringify({
      model: "gpt-image-1",
      prompt: `A photorealistic portrait of a ${animal}'s face looking directly at the camera, perfectly head-on and symmetrical, both eyes clearly visible and level, mouth closed, the head filling most of the frame, on a fully transparent background. Only the head — no body, no text.`,
      size: "1024x1024",
      quality: "medium",
      output_format: "png",
      background: "transparent",
    }),
  });
  if (!response.ok) throw new Error(`${animal}: ${response.status} ${await response.text()}`);
  const payload = await response.json();
  const raw = join(scratch, `${animal}.png`);
  writeFileSync(raw, Buffer.from(payload.data[0].b64_json, "base64"));
  execFileSync("sips", ["-Z", "448", raw, "--out", raw]);
  const base64 = readFileSync(raw).toString("base64");
  console.log(`${animal}: ${Math.round((base64.length * 3) / 4 / 1024)}KB`);
  return [animal, base64];
}

const results = [];
for (let i = 0; i < ANIMALS.length; i += 4) {
  results.push(...(await Promise.all(ANIMALS.slice(i, i + 4).map(generate))));
}

writeFileSync(
  outPath,
  `// Generated by scripts/generate-animal-faces.mjs — do not edit by hand.
// Photorealistic transparent-background animal face portraits for the
// Animal mask filter. ONLY import via lib/filters/definitions.ts (the
// DOM-component side) — this must not ride into the native Hermes bundle.

export const ANIMAL_FACE_IMAGES: Record<string, string> = {
${results.map(([animal, base64]) => `  ${JSON.stringify(animal)}:\n    "data:image/png;base64,${base64}",`).join("\n")}
};
`,
);
console.log(`wrote ${outPath} (${results.length} faces)`);
