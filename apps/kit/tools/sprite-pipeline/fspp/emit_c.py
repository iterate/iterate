"""FSPR v2 C emission.

Emits one translation unit per target atlas, structurally compatible with
firmware-ws/main/face_sprite_sheet.h: RGB565 palette, PackBits/raw cell
blob, cell table, shared mouth arrays, viseme maps, and expression banks,
rooted in a single const face_sprite_atlas_t. The layout mirrors
tools/generate_sprite_showcase.py so the production player and existing
review tooling accept the output unchanged.
"""

from __future__ import annotations

from .catalog import Bank, EyeLayer, TargetAtlas
from .util import rgb565
from .vocab import CELL_NONE, MOUTH_SLOT_NAMES

BANNER = (
    "/* Generated by tools/sprite-pipeline/avatar_pipeline.py. "
    "Do not hand-edit.\n"
    " * Derived sprite data is dedicated to the public domain under CC0 1.0\n"
    " * to the extent of the generator's contribution; see the pack README\n"
    " * for source-art provenance.\n"
    " */\n"
)

ATLAS_FLAG_NAMES = {
    "breathe": "FACE_SPRITE_ATLAS_BREATHE",
    "idle_saccades": "FACE_SPRITE_ATLAS_IDLE_SACCADES",
    "auto_blink": "FACE_SPRITE_ATLAS_AUTO_BLINK",
}


def _bytes_rows(data: bytes, indent: str = "    ") -> str:
    rows = []
    for index in range(0, len(data), 16):
        rows.append(
            indent
            + ", ".join(str(value) for value in data[index : index + 16])
            + ","
        )
    return "\n".join(rows)


def _words_rows(data: list[int], indent: str = "    ") -> str:
    rows = []
    for index in range(0, len(data), 8):
        rows.append(
            indent
            + ", ".join(f"0x{value:04x}" for value in data[index : index + 8])
            + ","
        )
    return "\n".join(rows)


def _cell_token(cell: int) -> str:
    return "FACE_SPRITE_CELL_NONE" if cell in (CELL_NONE, -1) else str(cell)


def _emit_eye(eye: EyeLayer) -> str:
    padded = list(eye.cells) + [-1] * (6 - len(eye.cells))
    return (
        f"{{ .x = {eye.x}, .y = {eye.y}, .cell_count = {len(eye.cells)}, "
        f".cells = {{ {', '.join(_cell_token(c) for c in padded)} }}, "
        ".flags = 0, .reserved = 0 }"
    )


def _emit_disabled_pupil() -> str:
    return (
        "{ .x = 0, .y = 0, .min_x = 0, .min_y = 0, .max_x = 0, .max_y = 0, "
        ".cell = FACE_SPRITE_CELL_NONE, .range_x = 0, .range_y = 0 }"
    )


def _emit_disabled_brow() -> str:
    return (
        "{ .x = 0, .y = 0, .cell_count = 0, "
        ".cells = { FACE_SPRITE_CELL_NONE, FACE_SPRITE_CELL_NONE, "
        "FACE_SPRITE_CELL_NONE, FACE_SPRITE_CELL_NONE, "
        "FACE_SPRITE_CELL_NONE }, .max_lift = 0, .flags = 0 }"
    )


def _emit_bank(atlas: TargetAtlas, bank: Bank) -> str:
    t = bank.target
    return (
        "    {\n"
        "        .target = { "
        f"{t.valence}, {t.arousal}, {t.mouth_corner}, "
        f"{t.brow_inner}, {t.eye_squint}, {{0, 0, 0}} "
        "},\n"
        f"        .base_cell = {bank.base_cell},\n"
        f"        .overlay_cell = {bank.overlay_cell},\n"
        "        .overlay_x = 0,\n"
        "        .overlay_y = 0,\n"
        f"        .mouth = {{ {bank.mouth_x}, {bank.mouth_y}, "
        f"{atlas.prefix}_mouths_{bank.mouth_array} }},\n"
        "        .eye_left = " + _emit_eye(bank.eye_left) + ",\n"
        "        .eye_right = " + _emit_eye(bank.eye_right) + ",\n"
        "        .pupil_left = " + _emit_disabled_pupil() + ",\n"
        "        .pupil_right = " + _emit_disabled_pupil() + ",\n"
        "        .brow_left = " + _emit_disabled_brow() + ",\n"
        "        .brow_right = " + _emit_disabled_brow() + ",\n"
        "    },"
    )


def _identifier(text: str) -> str:
    return "".join(character if character.isalnum() else "_" for character in text)


def _variant_symbol(atlas: TargetAtlas, variant_id: str) -> str:
    return f"{atlas.symbol}_{_identifier(variant_id)}"


def _emit_atlas_definition(
    atlas: TargetAtlas,
    symbol: str,
    palette_name: str,
    palette_count: int,
    background_565: int,
    display_name: str,
    flags_text: str,
    fallback_text: str,
) -> str:
    prefix = atlas.prefix
    return (
        f"const face_sprite_atlas_t {symbol} = {{\n"
        "    .magic = FACE_SPRITE_MAGIC,\n"
        "    .version = FACE_SPRITE_VERSION,\n"
        f"    .native_width = {atlas.canvas[0]},\n"
        f"    .native_height = {atlas.canvas[1]},\n"
        f"    .scale = {atlas.target.scale},\n"
        "    .transparent_index = 0,\n"
        f"    .palette_count = {palette_count},\n"
        f"    .cell_count = {len(atlas.cells)},\n"
        f"    .mouth_slot_count = {len(MOUTH_SLOT_NAMES)},\n"
        f"    .viseme_map_count = {len(atlas.viseme_map)},\n"
        f"    .bank_count = {len(atlas.banks)},\n"
        "    .sequence_count = 0,\n"
        "    .cycle_count = 0,\n"
        f"    .flags = {flags_text},\n"
        f"    .background = 0x{background_565:04x},\n"
        "    .reserved = 0,\n"
        "    .selector = FACE_SPRITE_SELECTOR_DEFAULTS,\n"
        "    .timing = FACE_SPRITE_TIMING_DEFAULTS,\n"
        f"    .fallback_slots = {{ {fallback_text} }},\n"
        "    .reserved_slots = {0, 0, 0},\n"
        f"    .palette = {palette_name},\n"
        f"    .cells = {prefix}_cells,\n"
        f"    .blob = {prefix}_blob,\n"
        f"    .blob_size = sizeof({prefix}_blob),\n"
        f"    .banks = {prefix}_banks,\n"
        f"    .viseme_map = {prefix}_visemes,\n"
        "    .sequences = NULL,\n"
        "    .cycles = NULL,\n"
        f'    .name = "{display_name}",\n'
        "};\n"
    )


def emit_atlas_c(atlas: TargetAtlas, background_565: int) -> str:
    prefix = atlas.prefix
    parts: list[str] = [BANNER, f'#include "{prefix}_atlas.h"\n']

    palette = atlas.palette.entries_565()
    parts.append(
        f"static const uint16_t {prefix}_palette[{len(palette)}] = {{\n"
        f"{_words_rows(palette)}\n"
        "};\n"
    )
    parts.append(
        f"static const uint8_t {prefix}_blob[{len(atlas.blob)}] = {{\n"
        f"{_bytes_rows(atlas.blob)}\n"
        "};\n"
    )
    cell_lines = []
    for cell, offset in zip(atlas.cells, atlas.cell_offsets):
        cell_lines.append(
            "    { "
            f"{cell.width}, {cell.height}, {cell.offset_x}, {cell.offset_y}, "
            f"{offset}, {len(cell.data)}, {cell.encoding}, {{0, 0, 0}} "
            "},"
        )
    parts.append(
        f"static const face_sprite_cell_t {prefix}_cells"
        f"[{len(atlas.cells)}] = {{\n" + "\n".join(cell_lines) + "\n};\n"
    )

    for index, slots in enumerate(atlas.mouth_arrays):
        parts.append(
            f"static const uint16_t {prefix}_mouths_{index}"
            f"[{len(slots)}] = {{\n    "
            + ", ".join(str(value) for value in slots)
            + ",\n};\n"
        )

    map_lines = [
        f"    {{ {viseme_set}, {viseme}, {slot}, {role} }},"
        for viseme_set, viseme, slot, role in atlas.viseme_map
    ]
    parts.append(
        f"static const face_sprite_viseme_map_t {prefix}_visemes"
        f"[{len(map_lines)}] = {{\n" + "\n".join(map_lines) + "\n};\n"
    )

    bank_lines = [_emit_bank(atlas, bank) for bank in atlas.banks]
    parts.append(
        f"static const face_sprite_bank_t {prefix}_banks"
        f"[{len(bank_lines)}] = {{\n" + "\n".join(bank_lines) + "\n};\n"
    )

    flag_tokens = [
        ATLAS_FLAG_NAMES[flag]
        for flag in atlas.flags
        if flag in ATLAS_FLAG_NAMES
    ]
    flags_text = " |\n        ".join(flag_tokens) if flag_tokens else "0"
    fallback_text = ", ".join(str(v) for v in atlas.fallback_slots)

    parts.append(
        _emit_atlas_definition(
            atlas,
            atlas.symbol,
            f"{prefix}_palette",
            len(palette),
            background_565,
            f"{atlas.spec.display_name} ({atlas.target.id})",
            flags_text,
            fallback_text,
        )
    )
    for variant in atlas.spec.palette.variants:
        variant_name = f"{prefix}_palette_{_identifier(variant.id)}"
        variant_palette = [0] + [rgb565(color) for color in variant.colors]
        parts.append(
            f"static const uint16_t {variant_name}"
            f"[{len(variant_palette)}] = {{\n"
            f"{_words_rows(variant_palette)}\n"
            "};\n"
        )
        parts.append(
            _emit_atlas_definition(
                atlas,
                _variant_symbol(atlas, variant.id),
                variant_name,
                len(variant_palette),
                rgb565(variant.background),
                f"{atlas.spec.display_name} · {variant.display_name} "
                f"({atlas.target.id})",
                flags_text,
                fallback_text,
            )
        )
    return "\n".join(parts)


def emit_atlas_h(atlas: TargetAtlas) -> str:
    variants = "".join(
        f"extern const face_sprite_atlas_t "
        f"{_variant_symbol(atlas, variant.id)};\n"
        for variant in atlas.spec.palette.variants
    )
    return (
        BANNER + "#pragma once\n\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n"
        '#include "face_sprite_sheet.h"\n\n'
        f"extern const face_sprite_atlas_t {atlas.symbol};\n"
        + variants
    )
