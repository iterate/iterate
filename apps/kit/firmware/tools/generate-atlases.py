# Minimal indexed-color PNG I/O (stdlib only)


def _png_chunk(tag: bytes, payload: bytes) -> bytes:
    return (
        struct.pack(">I", len(payload))
        + tag
        + payload
        + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)
    )


def png_write(path: Path, width: int, height: int, pixels: bytes, palette565: list[int]) -> None:
    """8-bit indexed PNG; PLTE is an RGB565->RGB888 expansion for viewing."""
    plte = bytearray()
    for value in palette565:
        r5, g6, b5 = (value >> 11) & 0x1F, (value >> 5) & 0x3F, value & 0x1F
        plte += bytes(((r5 << 3) | (r5 >> 2), (g6 << 2) | (g6 >> 4), (b5 << 3) | (b5 >> 2)))
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter: None
        raw += pixels[y * width : (y + 1) * width]
    out = b"\x89PNG\r\n\x1a\n"
    out += _png_chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 3, 0, 0, 0))
    out += _png_chunk(b"PLTE", bytes(plte))
    out += _png_chunk(b"tRNS", b"\x00")  # index 0 is transparent
    out += _png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    out += _png_chunk(b"IEND", b"")
    path.write_bytes(out)


def png_read(path: Path) -> tuple[int, int, bytes]:
    """Return (width, height, palette-index bytes). Indexed 8-bit only."""
    blob = path.read_bytes()
    if blob[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"{path}: not a PNG")
    pos, width, height, idat = 8, 0, 0, bytearray()
    while pos < len(blob):
        (length,) = struct.unpack(">I", blob[pos : pos + 4])
        tag = blob[pos + 4 : pos + 8]
        payload = blob[pos + 8 : pos + 8 + length]
        pos += 12 + length
        if tag == b"IHDR":
            width, height, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", payload)
            if (depth, color, interlace) != (8, 3, 0):
                raise ValueError(f"{path}: expected non-interlaced 8-bit indexed PNG")
        elif tag == b"IDAT":
            idat += payload
        elif tag == b"IEND":
            break
    raw = zlib.decompress(bytes(idat))
    stride = width + 1
    out = bytearray()
    prev = bytearray(width)
    for y in range(height):
        row = bytearray(raw[y * stride + 1 : (y + 1) * stride])
        filt = raw[y * stride]
        for x in range(width):
            a = row[x - 1] if x else 0
            b = prev[x]
            c = prev[x - 1] if x else 0
            if filt == 1:
                row[x] = (row[x] + a) & 0xFF
            elif filt == 2:
                row[x] = (row[x] + b) & 0xFF
            elif filt == 3:
                row[x] = (row[x] + (a + b) // 2) & 0xFF
            elif filt == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                row[x] = (row[x] + pred) & 0xFF
            elif filt != 0:
                raise ValueError(f"{path}: unsupported PNG filter {filt}")
        out += row
        prev = row
    return width, height, bytes(out)


