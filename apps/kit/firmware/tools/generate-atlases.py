#!/usr/bin/env python3
"""Regenerate the avatar sprite atlas C files from committed compact assets.

The five fspp_*_cores3_fine_atlas.c files (and the avatar catalog .inc) are
NOT committed - roughly 4,500 lines of machine-written hex nobody reviews.
What IS committed, per pack, in components/avatar/assets/:

  <pack>.png   one indexed-color sprite map holding every cell's pixels
               (palette index 0 is transparent; the PLTE colors are only a
               viewing aid - the authoritative RGB565 palette is in the JSON)
  <pack>.json  everything else: palette(s), cell geometry and sprite-map
               placement, mouth slot arrays, viseme maps, expression banks,
               both atlas structs' fields, and the catalog entry

Usage (stdlib python3 only, no dependencies):

  python3 apps/kit/firmware/tools/generate-atlases.py            # assets -> src
  python3 apps/kit/firmware/tools/generate-atlases.py extract    # src -> assets

`extract` is the inverse tool that produced the assets from the original
generated C in the first place; it round-trips through the emitter and fails
unless the regenerated C is byte-identical, so it is safe to re-run.

Cell pixels are stored decoded in the PNG. The generator re-encodes each cell
with the exact PackBits dialect face_sprite_sheet.c decodes (run >= 3 becomes
a repeat, literals break before a 3-run, raw wins ties) and rebuilds the blob
by concatenation, reproducing the original byte stream exactly.
"""

