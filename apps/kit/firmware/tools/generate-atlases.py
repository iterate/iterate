# --------------------------------------------------------------------------
# PackBits (the exact dialect decoded by face_sprite_sheet.c)


def packbits(data: bytes) -> bytes:
    result = bytearray()
    index = 0
    while index < len(data):
        run = 1
        while (
            index + run < len(data)
            and data[index + run] == data[index]
            and run < 128
        ):
            run += 1
        if run >= 3:
            result.append(257 - run)
            result.append(data[index])
            index += run
            continue
        start = index
        index += 1
        while index < len(data) and index - start < 128:
            if (
                index + 2 < len(data)
                and data[index] == data[index + 1] == data[index + 2]
            ):
                break
            index += 1
        literal = data[start:index]
        result.append(len(literal) - 1)
        result.extend(literal)
    return bytes(result)


def unpackbits(data: bytes, expected: int) -> bytes:
    out = bytearray()
    pos = 0
    while len(out) < expected:
        if pos >= len(data):
            raise ValueError("PackBits stream truncated")
        control = data[pos]
        pos += 1
        if control == 128:
            continue
        if control > 128:
            if pos >= len(data):
                raise ValueError("PackBits repeat missing byte")
            out.extend(bytes((data[pos],)) * (257 - control))
            pos += 1
        else:
            count = control + 1
            if pos + count > len(data):
                raise ValueError("PackBits literal truncated")
            out.extend(data[pos : pos + count])
            pos += count
    if len(out) != expected or pos != len(data):
        raise ValueError("PackBits stream does not end exactly at cell size")
    return bytes(out)


def encode_cell(pixels: bytes) -> tuple[bytes, int]:
    """Return (data, encoding): PackBits when strictly shorter, else raw."""
    encoded = packbits(pixels)
    if len(encoded) >= len(pixels):
        return pixels, 0
    return encoded, 1


