// Bundles packages/iterate/src/sdk.ts into ONE self-contained ESM module
// (zod and capnweb included, workerd conditions) and embeds it as a string.
// The worker loader injects it into every dynamic worker build as the
// `iterate/sdk` virtual module — the platform PROVIDES the SDK runtime, the
// exact build the deployed contract was generated from, so project workers
// never npm-install it. (The template's `iterate` devDependency stays: it is
// the TYPES for editors; the worker-bundler's npm installer only resolves
// registry semver deps and cannot fetch pkg.pr.new tarball URLs anyway —
// which is why the runtime must arrive as a virtual module.)
// Freshness is enforced by src/domains/workers/iterate-sdk-runtime.generated.test.ts.
//
// Regenerate: pnpm generate:iterate-sdk-runtime (after pnpm generate:itx-api)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildIterateSdkRuntimeModule } from "./iterate-sdk-runtime-bundle.ts";

const outPath = fileURLToPath(
  new URL("../src/domains/workers/iterate-sdk-runtime.generated.ts", import.meta.url),
);

const code = await buildIterateSdkRuntimeModule();
const escaped = code.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");

writeFileSync(
  outPath,
  `// GENERATED by scripts/generate-iterate-sdk-runtime.ts — do not edit.
// Regenerate with: pnpm generate:iterate-sdk-runtime
// Freshness is enforced by iterate-sdk-runtime.generated.test.ts.

/** packages/iterate/src/sdk.ts bundled self-contained (zod + capnweb included),
 * injected into every dynamic worker build as the \`iterate/sdk\` virtual module. */
export const ITERATE_SDK_RUNTIME_MODULE = \`${escaped}\`;
`,
);

console.log(`wrote ${outPath}`);
