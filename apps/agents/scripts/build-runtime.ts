import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

/** The committed template asset is rebuilt from this app's runtime. The platform's SDK is injected. */
export async function buildAgentRuntime(): Promise<string> {
  const result = await build({
    absWorkingDir: new URL("..", import.meta.url).pathname,
    entryPoints: [new URL("../runtime/index.ts", import.meta.url).pathname],
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    external: ["cloudflare:workers"],
    plugins: [
      {
        name: "injected-sdk",
        setup(builder) {
          builder.onResolve(
            { filter: /^(zod|iterate\/next\/(sdk|stream\/processor|stream\/run))$/ },
            () => ({ path: "./processor.js", external: true }),
          );
        },
      },
    ],
  });
  return (
    "// Generated by pnpm --dir apps/agents runtime:build. Do not edit.\n" +
    result.outputFiles[0]!.text
  );
}
if (process.argv[1]?.endsWith("build-runtime.ts")) {
  const path = new URL("../../../configs-next/with-agents/agents.js", import.meta.url).pathname;
  const source = await buildAgentRuntime();
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== source)
      throw new Error("The agents template is stale. Run pnpm --dir apps/agents runtime:build");
  } else {
    await writeFile(path, source);
  }
}
